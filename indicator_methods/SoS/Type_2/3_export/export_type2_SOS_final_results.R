# =======================================================================
# Export SoS and GAM significance results to Type 2 Excel files
# =======================================================================

# -----------------------------------------------------------------------
# Description
# -----------------------------------------------------------------------
# This script reads one Data_Ready CSV file generated from the Type 2 SoS
# workflow, extracts SoS values and GAM significance information, and
# writes them into the "Station information" sheet of the corresponding
# original Type 2 Excel file.
#
# The script is written as a reproducible example for GitHub. It exports
# one dataset only. To export another Type 2 dataset, change the user
# settings below: dataset_name, biological_component, data_ready_file,
# station_id_data_ready, station_id_excel and, when needed, the station
# transformation block.
#
# Example used here:
#   - Dataset: BS_gotland_btrawling
#   - Biological component: INFAUNA
#   - Data_Ready file: Data_Ready_BS_gotland_btrawling.csv
#
# For the selected Data_Ready file, the script extracts:
#   - station identifier
#   - PerTS_ByWeight, exported as SoS_2026
#   - gam_significant, when available
#   - gam_pvalue, when available
#
# It also creates a descriptive GAM relationship column:
#   - "significant"     if gam_significant = 1
#   - "not_significant" if gam_significant = 0
#
# The original source Excel file is not overwritten. A new Excel file is
# created in the final output folder.
#
# -----------------------------------------------------------------------
# Notes on Type 2 dataset-specific cases
# -----------------------------------------------------------------------
# Type 2 datasets are less standardised than Type 3 datasets. Before
# running the script for a new dataset, check the following points:
#
# 1. Station identifier
#    Some datasets can be merged directly by "station". Others require
#    "station_2", or a station identifier created from station, year and/or
#    replicate fields.
#
#    Examples:
#      - Standard case: merge by station.
#      - Gotland case: Data_Ready station codes starting with "GO" are
#        converted to "Gotland" and suffixes such as _2017_1 are removed.
#      - Kattegat case: station_2 may need to be created in the Excel file
#        as station_year_replicate.
#      - Sand-extraction datasets: station_2 may need to be created in the
#        Excel file as station_year.
#
# 2. Oxygen-depletion datasets
#    Datasets with "oxygendepletion" in the name use oxygen depletion as
#    the pressure variable, not SAR. The export logic is the same, but the
#    interpretation of GAM significance should refer to the oxygen-pressure
#    relationship.
#
# 3. Cumulative-pressure datasets
#    Some datasets combine bottom trawling and sand extraction. In those
#    cases, the Data_Ready file may contain pressure-specific GAM columns,
#    for example:
#      - gam_significant_trawling
#      - gam_pvalue_trawling
#      - gam_significant_sandextr
#      - gam_pvalue_sandextr
#
#    For those datasets, set cumulative_pressures <- TRUE and define the
#    pressure-specific columns in the user settings section.
#
# 4. GAM columns
#    The preferred option is to export GAM information directly from the
#    Data_Ready file. If gam_significant or gam_pvalue are not available,
#    either add them to the Data_Ready file before running this script or
#    set default values manually in the section "Add GAM information".
#
# -----------------------------------------------------------------------
# Required packages
# -----------------------------------------------------------------------
# - readxl
# - openxlsx

# -----------------------------------------------------------------------
# Load libraries
# -----------------------------------------------------------------------

library(readxl)
library(openxlsx)

# -----------------------------------------------------------------------
# User settings
# -----------------------------------------------------------------------

# Dataset name should be provided WITHOUT file extension
dataset_name <- "BS_gotland_btrawling"

# Biological component used in the Type 2 SoS workflow: "INFAUNA" or "EPIFAUNA"
biological_component <- "INFAUNA"

# Data_Ready CSV file to export for this dataset
data_ready_file <- "Data_Ready_BS_gotland_btrawling.csv"

# Folder containing original Type 2 Excel files
input_folder <- "../../../data/Type2"

# Folder containing Data_Ready CSV files generated by the Type 2 SoS workflow
data_ready_folder <- file.path(
  "../SoS/Type2/sos_output",
  biological_component,
  dataset_name
)

# Output folder for exported Excel files
output_folder <- "../../SoS/Type2/final_output"

if (!dir.exists(output_folder)) {
  dir.create(output_folder, recursive = TRUE)
}

# Input and output Excel files
input_xlsx <- file.path(input_folder, paste0(dataset_name, ".xlsx"))
output_xlsx <- file.path(output_folder, paste0(dataset_name, "_SoS_export.xlsx"))

# Full path to Data_Ready CSV file
input_csv <- file.path(data_ready_folder, data_ready_file)

# Sheet containing the station metadata in the original Excel file
station_sheet <- "Station information"

# Column used as station identifier in the Data_Ready file
station_id_data_ready <- "station_2"

# Column used as station identifier in the Excel Station information sheet
station_id_excel <- "station"

# Set to TRUE only for datasets with pressure-specific GAM results
# such as trawling + sand extraction.
cumulative_pressures <- FALSE

# Pressure-specific GAM columns used only if cumulative_pressures = TRUE
pressure_gam_columns <- c(
  "gam_significant_trawling",
  "gam_pvalue_trawling",
  "gam_significant_sandextr",
  "gam_pvalue_sandextr"
)

# -----------------------------------------------------------------------
# Check input paths
# -----------------------------------------------------------------------

if (!file.exists(input_xlsx)) {
  stop(paste("Input Excel file not found:", input_xlsx))
}

if (!file.exists(input_csv)) {
  stop(paste("Data_Ready CSV file not found:", input_csv))
}

# -----------------------------------------------------------------------
# Read Data_Ready CSV file
# -----------------------------------------------------------------------

data_ready <- read.csv(input_csv, stringsAsFactors = FALSE)

# Check required columns
required_cols <- c(station_id_data_ready, "PerTS_ByWeight")
missing_cols <- setdiff(required_cols, names(data_ready))

if (length(missing_cols) > 0) {
  stop(
    paste(
      "The following required columns are missing from the Data_Ready file:",
      paste(missing_cols, collapse = ", ")
    )
  )
}

# Keep station identifier and SoS column
data_export <- data_ready[, required_cols]
names(data_export)[names(data_export) == station_id_data_ready] <- "station_export_id"
names(data_export)[names(data_export) == "PerTS_ByWeight"] <- "SoS_2026"

# -----------------------------------------------------------------------
# Add GAM information
# -----------------------------------------------------------------------

if (!cumulative_pressures) {

  # Preferred option: read GAM information directly from Data_Ready
  if ("gam_significant" %in% names(data_ready)) {
    data_export$gam_significant <- data_ready$gam_significant
  } else {
    # Fallback option: set manually only if the Data_Ready file does not
    # contain gam_significant. Change this value if required.
    data_export$gam_significant <- 0
  }

  if ("gam_pvalue" %in% names(data_ready)) {
    data_export$gam_pvalue <- data_ready$gam_pvalue
  }

  data_export$gam_relationship <- ifelse(
    data_export$gam_significant == 1,
    "significant",
    "not_significant"
  )

} else {

  # Cumulative-pressure case: export pressure-specific GAM information.
  missing_pressure_cols <- setdiff(pressure_gam_columns, names(data_ready))

  if (length(missing_pressure_cols) > 0) {
    stop(
      paste(
        "The following pressure-specific GAM columns are missing:",
        paste(missing_pressure_cols, collapse = ", ")
      )
    )
  }

  data_export <- cbind(
    data_export,
    data_ready[, pressure_gam_columns]
  )

  data_export$gam_relationship_trawling <- ifelse(
    data_export$gam_significant_trawling == 1,
    "significant",
    "not_significant"
  )

  data_export$gam_relationship_sandextr <- ifelse(
    data_export$gam_significant_sandextr == 1,
    "significant",
    "not_significant"
  )
}

# -----------------------------------------------------------------------
# Dataset-specific station transformations
# -----------------------------------------------------------------------
# This block is intentionally explicit because Type 2 datasets often need
# small dataset-specific adaptations before merging.

if (dataset_name == "BS_gotland_btrawling") {

  # Convert only the first "GO" prefix into "Gotland".
  # Examples:
  #   GO_3129  -> Gotland_3129
  #   GO_GO10  -> Gotland_GO10
  data_export$station_export_id <- sub(
    "^(?i)go",
    "Gotland",
    data_export$station_export_id,
    perl = TRUE
  )

  # Remove year/replicate suffixes when present.
  # Example:
  #   Gotland_3129_2017_1 -> Gotland_3129
  data_export$station_export_id <- sub(
    "_[0-9]{4}_[0-9]+$",
    "",
    data_export$station_export_id
  )
}

# Remove duplicated rows if present
data_export <- unique(data_export)

# -----------------------------------------------------------------------
# Read Station information sheet from original Excel file
# -----------------------------------------------------------------------
# Check the exact name of the sheet in the Excel file before reading it.
# It may be "Station information", "station_information", or another
# variant depending on the dataset. Use excel_sheets(input_xlsx) to verify.

station_info <- read_excel(input_xlsx, sheet = station_sheet)

# For some datasets, the merge identifier must be created in the Excel
# Station information sheet before merging. Uncomment and adapt as needed.

# Example for Kattegat-like datasets:
# station_info$station_2 <- paste(
#   trimws(as.character(station_info$station)),
#   trimws(as.character(station_info$year)),
#   trimws(as.character(station_info$replicates)),
#   sep = "_"
# )
# station_id_excel <- "station_2"

# Example for sand-extraction datasets:
# station_info$station_2 <- paste(
#   trimws(as.character(station_info$station)),
#   trimws(as.character(station_info$year)),
#   sep = "_"
# )
# station_id_excel <- "station_2"

if (!station_id_excel %in% names(station_info)) {
  stop(paste("Station identifier not found in Excel sheet:", station_id_excel))
}

# Remove previous export columns if already present
cols_to_replace <- c(
  "SoS_2026",
  "gam_significant",
  "gam_pvalue",
  "gam_relationship",
  "gam_significant_trawling",
  "gam_pvalue_trawling",
  "gam_relationship_trawling",
  "gam_significant_sandextr",
  "gam_pvalue_sandextr",
  "gam_relationship_sandextr"
)

station_info <- station_info[, !(names(station_info) %in% cols_to_replace)]

# -----------------------------------------------------------------------
# Merge SoS information into Station information
# -----------------------------------------------------------------------

names(station_info)[names(station_info) == station_id_excel] <- "station_export_id"

station_info_updated <- merge(
  station_info,
  data_export,
  by = "station_export_id",
  all.x = TRUE
)

names(station_info_updated)[names(station_info_updated) == "station_export_id"] <- station_id_excel

# -----------------------------------------------------------------------
# Write updated Station information into a new Excel file
# -----------------------------------------------------------------------

wb <- loadWorkbook(input_xlsx)

writeData(
  wb,
  sheet = station_sheet,
  x = station_info_updated
)

saveWorkbook(wb, output_xlsx, overwrite = TRUE)

# -----------------------------------------------------------------------
# Final message
# -----------------------------------------------------------------------

cat("------------------------------------------------------------\n")
cat("Type 2 export completed successfully.\n")
cat("Dataset:", dataset_name, "\n")
cat("Input Excel file:\n", input_xlsx, "\n")
cat("Data_Ready CSV file:\n", input_csv, "\n")
cat("Output Excel file:\n", output_xlsx, "\n")
cat("Rows exported:", nrow(data_export), "\n")
cat("Done.\n")
